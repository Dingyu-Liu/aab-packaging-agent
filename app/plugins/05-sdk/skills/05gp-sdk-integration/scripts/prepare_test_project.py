#!/usr/bin/env python3
"""Copy an Android project into a new, isolated project for a test APK.

Python 3.9+ and a JDK providing keytool are required. This helper never edits the
source project, runs Gradle, connects to a device, or contacts a network. PA and
Adjust inputs are intentionally ignored: the agent must configure the desired
SDK behavior in the source/working integration before using this copy helper.

Usage:
    python3 prepare_test_project.py --config resolved.json --destination /abs/new

The printed Gradle command must be used for this test copy. The generated init
script changes the applicationId/signing only during that invocation; opening
the copy in Android Studio without the init script does not activate them.
Product flavors require a project-specific adaptation and are rejected by the
init script. Existing source signing declarations are preserved. Keys are
excluded only at recognized root/module signing locations; suspicious key files
or signing directories in source/resource trees cause a pre-copy error instead
of silently changing application assets. The test build uses a new local key.
"""

import argparse
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
from typing import Any, Dict, Iterable, Optional, Set


class PreparationError(Exception):
    """An actionable error whose message never contains input secrets."""


PACKAGE_RE = re.compile(r"[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z][A-Za-z0-9_]*)+\Z")
MODULE_RE = re.compile(r":[A-Za-z0-9_][A-Za-z0-9_.-]*(?::[A-Za-z0-9_][A-Za-z0-9_.-]*)*\Z")
BUILD_TYPE_RE = re.compile(r"[A-Za-z][A-Za-z0-9_]*\Z")
CACHE_NAMES = {"build", ".gradle", ".cxx", ".idea", ".git"}
KEY_DIRECTORY_NAMES = {"keystore", "keystores", "test-signing"}
KEY_EXTENSIONS = {".keystore", ".jks", ".jceks", ".bks", ".p12", ".pfx", ".pkcs12", ".key", ".pk8", ".p8"}
KEY_FILE_NAMES = {"id_rsa", "id_dsa", "id_ecdsa", "id_ed25519"}

# This init script consumes only the sanitized descriptor next to settings.gradle.
# finalizeDsl applies after the project's normal DSL so a signing assignment in
# the module's build file cannot silently restore the production signing config.
INIT_SCRIPT = '''// Generated by prepare_test_project.py. Dedicated test build only.
// Invoke Gradle with --init-script gp-test.init.gradle; see gp-test-build.json.
import groovy.json.JsonSlurper

gradle.settingsEvaluated { settings ->
    def descriptorFile = new File(settings.settingsDir, 'gp-test-build.json')
    if (!descriptorFile.isFile()) {
        throw new GradleException('Test descriptor is missing; run from the prepared project root.')
    }
    def spec = new JsonSlurper().parse(descriptorFile)
    def targetModule = spec.build.module as String
    def applicationModuleSeen = false

    gradle.beforeProject { targetProject ->
        if (targetProject.path == targetModule) {
            targetProject.pluginManager.withPlugin('com.android.application') {
                applicationModuleSeen = true
                def components = targetProject.extensions.findByName('androidComponents')
                if (components == null) {
                    throw new GradleException('This test override requires an AGP androidComponents.finalizeDsl API.')
                }
                components.finalizeDsl { android ->
                    if (!android.productFlavors.isEmpty()) {
                        throw new GradleException('Product flavors are not supported by this generic test helper. Adapt the selected variant explicitly before building.')
                    }
                    def existingId = android.defaultConfig.applicationId ?: android.namespace
                    if (existingId != spec.production_application_id) {
                        throw new GradleException('The supplied production_application_id does not match the application module. Inspect the project configuration before making a test build.')
                    }
                    def selectedType = android.buildTypes.findByName(spec.build.build_type as String)
                    if (selectedType == null) {
                        throw new GradleException('The selected test build type does not exist in the application module.')
                    }
                    def testKey = new File(settings.settingsDir, 'test-signing/debug.keystore')
                    if (!testKey.isFile()) {
                        throw new GradleException('Dedicated test signing key is missing.')
                    }
                    def testSigning = android.signingConfigs.findByName('gpSdkTest')
                    if (testSigning == null) {
                        testSigning = android.signingConfigs.create('gpSdkTest')
                    }
                    testSigning.storeFile = testKey
                    testSigning.storePassword = 'android'
                    testSigning.keyAlias = 'androiddebugkey'
                    testSigning.keyPassword = 'android'
                    testSigning.storeType = 'JKS'
                    android.defaultConfig.applicationId = spec.test_application_id as String
                    if (spec.app_version_name != null) {
                        android.defaultConfig.versionName = spec.app_version_name as String
                    }
                    if (spec.app_version_code != null) {
                        android.defaultConfig.versionCode = (spec.app_version_code as Number).intValue()
                    }
                    selectedType.applicationIdSuffix = ''
                    selectedType.signingConfig = testSigning
                    logger.lifecycle('GP SDK test build: applicationId={}, module={}, buildType={}',
                            spec.test_application_id, targetModule, spec.build.build_type)
                }
            }
        }
    }
    gradle.projectsEvaluated {
        if (!applicationModuleSeen) {
            throw new GradleException('The selected module was not found or does not apply com.android.application.')
        }
    }
}
'''


def is_within(path: Path, parent: Path) -> bool:
    return path == parent or parent in path.parents


def absolute_path(value: Any, field: str, must_exist: bool = False) -> Path:
    if not isinstance(value, str) or not value or not Path(value).is_absolute():
        raise PreparationError(field + ' must be an absolute path.')
    try:
        result = Path(value).resolve(strict=must_exist)
    except (OSError, RuntimeError):
        raise PreparationError(field + ' could not be resolved.') from None
    return result


def package_id(value: Any, field: str) -> str:
    if not isinstance(value, str) or not PACKAGE_RE.fullmatch(value):
        raise PreparationError(field + ' must be an Android applicationId with at least two valid segments.')
    return value


def load_config(config_path: Path) -> Dict[str, Any]:
    try:
        with config_path.open('r', encoding='utf-8-sig') as stream:
            raw = json.load(stream)
    except (OSError, ValueError):
        raise PreparationError('Cannot read the configuration as a JSON object.') from None
    if not isinstance(raw, dict):
        raise PreparationError('The configuration must be a JSON object.')

    source = absolute_path(raw.get('project_dir'), 'project_dir', must_exist=True)
    if not source.is_dir():
        raise PreparationError('project_dir must be a directory.')
    if not any((source / name).is_file() for name in ('settings.gradle', 'settings.gradle.kts')):
        raise PreparationError('project_dir must be the Gradle project root containing settings.gradle or settings.gradle.kts.')
    if any(source.glob('gp-test*')):
        raise PreparationError('The source already contains gp-test* entries. Use the original project or inspect the earlier test preparation first.')

    production_id = package_id(raw.get('production_application_id'), 'production_application_id')
    test_id_raw = raw.get('test_application_id')
    test_id = package_id(production_id + '.sdktest' if test_id_raw is None else test_id_raw,
                         'test_application_id')
    if test_id == production_id:
        raise PreparationError('test_application_id must differ from production_application_id.')

    version_name = raw.get('app_version_name')
    if version_name is not None and (not isinstance(version_name, str) or not version_name.strip()):
        raise PreparationError('app_version_name must be a nonempty string or null.')
    version_code = raw.get('app_version_code')
    if version_code is not None and (isinstance(version_code, bool) or not isinstance(version_code, int)
                                     or not 1 <= version_code <= 2100000000):
        raise PreparationError('app_version_code must be an integer from 1 to 2100000000 or null.')

    build = raw.get('build')
    if build is None:
        build = {}
    if not isinstance(build, dict):
        raise PreparationError('build must be an object or null.')
    module = build.get('module', ':launcher')
    if not isinstance(module, str) or not MODULE_RE.fullmatch(module):
        raise PreparationError('build.module must be a Gradle application module path such as :launcher or :app.')
    build_type = build.get('build_type', 'debug')
    if not isinstance(build_type, str) or not BUILD_TYPE_RE.fullmatch(build_type):
        raise PreparationError('build.build_type must be a simple Gradle build type name.')
    sdk_raw = build.get('sdk_dir')
    sdk_dir: Optional[Path] = None
    if sdk_raw is not None:
        sdk_dir = absolute_path(sdk_raw, 'build.sdk_dir', must_exist=True)
        if not sdk_dir.is_dir():
            raise PreparationError('build.sdk_dir must be an existing directory or null.')

    # Whitelist fields: PA/Adjust/Maven values in raw are never copied to metadata,
    # logged, executed, or used to alter the SDK configuration.
    return {
        'source': source,
        'production_application_id': production_id,
        'test_application_id': test_id,
        'app_version_name': version_name,
        'app_version_code': version_code,
        'build': {'module': module, 'build_type': build_type},
        'sdk_dir': sdk_dir,
    }


def discover_cache_roots(source: Path, module: str) -> Set[Path]:
    """Only recognize root/direct module caches, never a generic **/build rule."""
    roots = {source}
    for child in source.iterdir():
        if child.is_dir() and not child.is_symlink() and any(
            (child / build_file).is_file() for build_file in ('build.gradle', 'build.gradle.kts')
        ):
            roots.add(child)
    # A selected conventional nested module may also have top-level caches.
    candidate = source.joinpath(*module.lstrip(':').split(':'))
    if candidate.is_dir() and not candidate.is_symlink() and any(
        (candidate / name).is_file() for name in ('build.gradle', 'build.gradle.kts')
    ):
        roots.add(candidate)
    return roots


def is_private_key(path: Path) -> bool:
    if path.suffix.lower() in KEY_EXTENSIONS or path.name.lower() in KEY_FILE_NAMES:
        return True
    # PEM public certificates can be application assets, so retain them; a PEM
    # private key must never be copied even if its filename is unconventional.
    if path.suffix.lower() in {'.pem', '.txt'} and path.is_file():
        try:
            with path.open('rb') as stream:
                return b'PRIVATE KEY-----' in stream.read(8192)
        except OSError:
            raise PreparationError('Cannot inspect a possible private key file.') from None
    return False


def build_ignore(source: Path, cache_roots: Set[Path], omitted_paths: Dict[str, str]):
    def note(entry: Path, reason: str, omitted: Set[str]) -> None:
        omitted.add(entry.name)
        omitted_paths[entry.relative_to(source).as_posix()] = reason

    def signing_entry(entry: Path, omitted: Set[str]) -> None:
        # An extension such as .p12/.key can also be a runtime asset. Only direct
        # root/module files and standard root/module signing directories can be
        # classified as signing material by this generic helper. Everywhere else
        # must be inspected/adapted, never silently stripped from the application.
        if entry.parent not in cache_roots:
            relative = json.dumps(entry.relative_to(source).as_posix(), ensure_ascii=False)
            raise PreparationError(
                'Possible key/signing entry outside a standard root/module signing location: '
                + relative + '. No destination has been created. Inspect its runtime purpose '
                'and adapt a project-specific variant/copy rule before retrying; do not silently omit application resources.'
            )
        note(entry, 'signing_material', omitted)

    def ignore(directory: str, names: Iterable[str]) -> Set[str]:
        parent = Path(directory)
        omitted: Set[str] = set()
        for name in names:
            entry = parent / name
            if parent in cache_roots and name in CACHE_NAMES:
                note(entry, 'build_cache', omitted)
            elif parent == source / 'launcher' and name == 'release':
                note(entry, 'historical_package_output', omitted)
            elif name.lower() in KEY_DIRECTORY_NAMES and entry.is_dir():
                signing_entry(entry, omitted)
            elif is_private_key(entry):
                signing_entry(entry, omitted)
            elif entry.is_symlink():
                try:
                    target = entry.resolve(strict=True)
                except (OSError, RuntimeError):
                    raise PreparationError('The source has a broken or cyclic symlink. Resolve it before preparing a test copy.') from None
                if not is_within(target, source):
                    raise PreparationError('The source has a symlink pointing outside the project. Materialize the needed files in a working project before preparing a test copy.')
                if is_private_key(target) or (target.is_dir() and target.name.lower() in KEY_DIRECTORY_NAMES):
                    signing_entry(entry, omitted)
        return omitted
    return ignore


def preflight_tree(directory: Path, ignore, ancestors: Optional[Set[Path]] = None) -> None:
    """Validate followed symlinks before copytree can duplicate an external path."""
    canonical = directory.resolve(strict=True)
    previous = set() if ancestors is None else ancestors
    if canonical in previous:
        raise PreparationError('The source has a directory symlink cycle. Resolve it before preparing a test copy.')
    parents = previous | {canonical}
    try:
        names = os.listdir(directory)
        omitted = ignore(str(directory), names)
        for name in names:
            if name in omitted:
                continue
            entry = directory / name
            if entry.is_dir():
                preflight_tree(entry, ignore, parents)
            elif not entry.is_file():
                raise PreparationError('The source contains a special file that cannot be copied as an independent test project.')
    except OSError:
        raise PreparationError('Cannot inspect all source project files.') from None


def locate_keytool() -> str:
    java_home = os.environ.get('JAVA_HOME')
    if java_home:
        candidate = Path(java_home) / 'bin' / ('keytool.exe' if os.name == 'nt' else 'keytool')
        if candidate.is_file():
            return str(candidate)
    keytool = shutil.which('keytool')
    if not keytool:
        raise PreparationError('A JDK keytool is required. Set JAVA_HOME to a JDK or put keytool on PATH.')
    return keytool


def properties_escape(value: str) -> str:
    """Escape a single Java .properties value without shell interpolation."""
    out = []
    for index, character in enumerate(value):
        if character == '\\':
            out.append('\\\\')
        elif character in ':=#!' or (index == 0 and character == ' '):
            out.append('\\' + character)
        elif character == '\n':
            out.append('\\n')
        elif character == '\r':
            out.append('\\r')
        elif character == '\t':
            out.append('\\t')
        else:
            out.append(character)
    return ''.join(out)


def secure_local_properties(destination: Path) -> None:
    for directory, subdirs, files in os.walk(destination, followlinks=False):
        # No symlinks survive copytree; do not traverse any future additions.
        subdirs[:] = [name for name in subdirs if not (Path(directory) / name).is_symlink()]
        for name in files:
            lower = name.lower()
            if (lower.endswith('.properties') and ('maven' in lower or lower in {'local.properties', 'gradle.properties'})):
                os.chmod(Path(directory) / name, 0o600)


def prepare(config: Dict[str, Any], destination_arg: str) -> Dict[str, Any]:
    source: Path = config['source']
    lexical_destination = Path(destination_arg)
    if not lexical_destination.is_absolute():
        raise PreparationError('destination must be an absolute path for a new directory.')
    if os.path.lexists(str(lexical_destination)):
        raise PreparationError('The destination already exists. Choose a new directory; existing paths are never overwritten.')
    destination = absolute_path(destination_arg, 'destination')
    if is_within(destination, source) or is_within(source, destination):
        raise PreparationError('The destination must be separate from the source and cannot be its parent or child.')

    keytool = locate_keytool()
    cache_roots = discover_cache_roots(source, config['build']['module'])
    omitted_paths: Dict[str, str] = {}
    ignore = build_ignore(source, cache_roots, omitted_paths)
    preflight_tree(source, ignore)

    # No rollback/removal is attempted on errors: a partial copy remains available
    # for inspection, and no unrelated path can be deleted accidentally.
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source, destination, symlinks=False, ignore=ignore)
    sdk_dir = config['sdk_dir']
    if sdk_dir is not None:
        (destination / 'local.properties').write_text(
            '# Local SDK path for this isolated test project.\n'
            + 'sdk.dir=' + properties_escape(str(sdk_dir)) + '\n', encoding='utf-8'
        )
    secure_local_properties(destination)

    signing_dir = destination / 'test-signing'
    signing_dir.mkdir(mode=0o700)
    key_file = signing_dir / 'debug.keystore'
    result = subprocess.run([
        keytool, '-genkeypair', '-keystore', str(key_file),
        '-storetype', 'JKS', '-storepass', 'android', '-keypass', 'android',
        '-alias', 'androiddebugkey', '-keyalg', 'RSA', '-keysize', '2048',
        '-validity', '10000', '-dname', 'CN=GP SDK Test,O=Local Test,C=US', '-noprompt',
    ], stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True, check=False)
    if result.returncode != 0 or not key_file.is_file():
        raise PreparationError('JDK keytool could not create the dedicated test key. The partial destination is retained; inspect JAVA_HOME before retrying into a new destination.')
    os.chmod(key_file, 0o600)

    build = config['build']
    task = build['module'] + ':assemble' + build['build_type'][0].upper() + build['build_type'][1:]
    descriptor: Dict[str, Any] = {
        'schema_version': 1,
        'production_application_id': config['production_application_id'],
        'test_application_id': config['test_application_id'],
        'app_version_name': config['app_version_name'],
        'app_version_code': config['app_version_code'],
        'build': dict(build),
        'gradle_task': task,
        'test_signing': {
            'keystore': 'test-signing/debug.keystore',
            'alias': 'androiddebugkey',
            'password_policy': 'Standard android password; dedicated local test signing only.',
        },
        'activation': 'Pass --init-script gp-test.init.gradle for every test build.',
        'omitted_paths': [
            {'path': relative, 'reason': reason}
            for relative, reason in sorted(omitted_paths.items())
        ],
        'unchanged': ['namespace', 'minSdk', 'targetSdk', 'abiFilters', 'PA configuration', 'Adjust environment and event mapping'],
    }
    (destination / 'gp-test-build.json').write_text(
        json.dumps(descriptor, ensure_ascii=False, indent=2) + '\n', encoding='utf-8'
    )
    (destination / 'gp-test.init.gradle').write_text(INIT_SCRIPT, encoding='utf-8')

    wrapper = destination / ('gradlew.bat' if os.name == 'nt' else 'gradlew')
    executable = str(wrapper) if wrapper.is_file() else 'gradle'
    command = shlex.join([
        executable, '--project-dir', str(destination), '--init-script',
        str(destination / 'gp-test.init.gradle'), task, '--console=plain',
    ])
    return {
        'status': 'prepared_not_built',
        'destination': str(destination),
        'manifest': descriptor,
        'build_command': command,
        'next_step': 'Run the command in the configured build environment, then verify the final APK package, version, minSdk, SDK configuration, and test signing certificate before delivery. No APK has been built or installed by this helper.',
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--config', required=True, type=Path, help='JSON inputs; unknown PA/Adjust fields are ignored.')
    parser.add_argument('--destination', required=True, help='Absolute, new directory separate from the source project.')
    args = parser.parse_args()
    try:
        prepared = prepare(load_config(args.config), args.destination)
    except PreparationError as error:
        print('ERROR: ' + str(error), file=sys.stderr)
        return 2
    except (OSError, shutil.Error, subprocess.SubprocessError):
        print('ERROR: Test project preparation failed. No source file was edited. Any partial destination is retained for inspection; retry only with a new destination after resolving the cause.', file=sys.stderr)
        return 2
    print(json.dumps(prepared, ensure_ascii=False, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
